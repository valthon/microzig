#!/usr/bin/env python3
"""Generate PMU vectors by compiling ESP-IDF v5.5.1 itself on the host.

The unmodified pmu_param.c, pmu_sleep.c, pmu_init.c and pmu_hal.c run against
RAM registers packed by IDF's own pmu_ll.h and pmu_struct.h. Shims supply only
platform plumbing, eFuse inputs and the Q13.19 RTC conversion. No HAL or SVD
is read. IDF is required only for regeneration, never for zig build test.
"""
import argparse
import os
from pathlib import Path
import subprocess
import tempfile

HERE = Path(__file__).resolve().parent
DEST = HERE.parents[3] / 'port/espressif/esp/src/hal/pmu_c6_idf_vectors.zon'
SHIMS = {'esp_attr.h': '#define FORCE_INLINE_ATTR static inline __attribute__((always_inline))\n'
               '#define IRAM_ATTR\n'
               '#define DRAM_ATTR\n',
 'esp_err.h': '',
 'esp_hw_log.h': '#define ESP_HW_LOGD(...)\n',
 'esp_private/ocode_init.h': 'static inline void esp_ocode_calib_init(void) {}\n',
 'esp_rom_sys.h': '#define RESET_REASON_CHIP_POWER_ON 1\n'
                  'static inline int esp_rom_get_reset_reason(int cpu) { return 0; }\n',
 'esp_types.h': '#include <stdint.h>\n'
                '#include <stdbool.h>\n'
                '#include <assert.h>\n'
                '#include <inttypes.h>\n',
 'hal/efuse_hal.h': 'static inline uint32_t efuse_hal_blk_version(void) { return fuse_version; }\n',
 'hal/efuse_ll.h': '#include <stdint.h>\n'
                   'extern uint32_t fuse_version, fuse_hp, fuse_lp, fuse_dbg, fuse_deep_lp;\n'
                   'static inline uint32_t efuse_ll_get_active_hp_dbias(void) { return fuse_hp; }\n'
                   'static inline uint32_t efuse_ll_get_active_lp_dbias(void) { return fuse_lp; }\n'
                   'static inline uint32_t efuse_ll_get_dslp_dbg(void) { return fuse_dbg; }\n'
                   'static inline uint32_t efuse_ll_get_dslp_lp_dbias(void) { return fuse_deep_lp; '
                   '}\n'
                   'static inline uint32_t efuse_ll_get_lslp_dbg(void) { return 0; }\n'
                   'static inline uint32_t efuse_ll_get_lslp_hp_dbias(void) { return 1; }\n'
                   '#define EFUSE_CONTROLLER_STATE_IDLE 1\n'
                   'static inline uint32_t efuse_ll_get_controller_state(void) { return 1; }\n',
 'hal/lp_aon_hal.h': 'static inline void lp_aon_hal_inform_wakeup_type(bool deep) { (void)deep; '
                     '}\n',
 'hal/misc.h': '#define HAL_FORCE_MODIFY_U32_REG_FIELD(reg, field, value) ((reg).field = (value))\n'
               '#define HAL_FORCE_READ_U32_REG_FIELD(reg, field) ((reg).field)\n',
 'hal/regi2c_ctrl_ll.h': '',
 'regi2c_ctrl.h': '#define REGI2C_WRITE_MASK(...) ((void)0)\n',
 'sdkconfig.h': '#define CONFIG_IDF_TARGET_ESP32C6 1\n',
 'soc/rtc.h': '#include "soc/clk_tree_defs.h"\n'
              'static inline uint64_t rtc_time_us_to_slowclk(uint64_t us, uint32_t period) { '
              'return (us << 19) / period; }\n'
              'static inline uint64_t rtc_time_slowclk_to_us(uint64_t ticks, uint32_t period) { '
              'return (ticks * period) >> 19; }\n',
 'soc/soc.h': '#include <stdint.h>\n'
              '#define BIT(n) (1U << (n))\n'
              '#define REG_READ(r) 0\n'
              '#define REG_WRITE(r,v) ((void)0)\n'
              '#define REG_GET_FIELD(r,f) 0\n'
              '#define REG_SET_FIELD(r,f,v) ((void)0)\n'
              '#define DR_REG_PMU_BASE 0\n'}


def build_runner(idf, temp):
    components = idf / 'components'
    for name, content in SHIMS.items():
        path = temp / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    include = [temp] + [components / p for p in (
        'esp_hw_support/port/esp32c6/private_include', 'esp_hw_support/include',
        'hal/esp32c6/include', 'hal/include', 'hal/platform_port/include',
        'soc/esp32c6/include', 'soc/esp32c6/register', 'soc/include', 'esp_common/include')]
    sources = [components / p for p in (
        'esp_hw_support/port/esp32c6/pmu_param.c',
        'esp_hw_support/port/esp32c6/pmu_sleep.c', 'hal/esp32c6/pmu_hal.c')]
    executable = temp / 'pmu-reference'
    subprocess.run([os.environ.get('CC', 'cc'), '-std=gnu11', '-Wall', '-Werror',
                    '-ffunction-sections', '-fdata-sections', '-Wl,--gc-sections',
                    '-DIDF_PMU_INIT="' + str(components / 'esp_hw_support/port/esp32c6/pmu_init.c') + '"',
                    *['-I' + str(p) for p in include], *map(str, sources),
                    str(HERE / 'sleep_c6_idf_host.c'), '-o', str(executable)], check=True)
    return executable


def generate(runner):
    lines = ['// Generated by examples/espressif/esp/tools/sleep_c6_idf_reference.py.',
             '// Computed by unmodified ESP-IDF v5.5.1 C sources and LL headers.', '.{']
    for label, slow, fast, fuses in [
        ('default', 3495253, 26214, (0, 0, 0, 0, 0)),
        ('calibrated', 3200000, 30000, (3, 22, 24, 3, 5)),
        ('saturated', 16000000, 32768, (100, 31, 0, 7, 15)),
    ]:
        for deep, xtal_off, mode in [(False, False, 'light'), (True, True, 'deep'), (False, True, 'light_xtal_off')]:
            output = subprocess.check_output([str(runner), *map(str, fuses), str(slow), str(fast), str(int(deep)), str(int(xtal_off))], text=True).splitlines()
            bias = tuple(map(int, output[0].split()[1:]))
            split = output.index('SLEEP')
            init_words = [line.split() for line in output[2:split]]
            words = [line.split() for line in output[split+1:]]
            init = {name: int(value, 16) for name, mask, value in init_words}
            lines += ['    .{', f'        .name = "{label}_{mode}",',
                      f'        .slow = {slow},',
                      f'        .fast = {fast},',
                      f'        .deep = {str(deep).lower()},',
                      f'        .xtal_off = {str(xtal_off).lower()},',
                      '        .fuses = .{ .version = %d, .hp = %d, .lp = %d, .deep_dbg = %d, .deep_lp = %d },' % fuses,
                      '        .bias = .{ .hp = %d, .lp = %d, .deep_dbg = %d, .deep_lp = %d },' % bias,
                      '        .init = .{ .hp_active = 0x%08x, .hp_modem = 0x%08x, .lp_active = 0x%08x },' % (init['HP_ACTIVE_HP_REGULATOR0'], init['HP_MODEM_HP_REGULATOR0'], init['HP_SLEEP_LP_REGULATOR0'])]
            for field, rows in [('init_words', init_words), ('words', words)]:
                lines.append('        .' + field + ' = .{')
                for name, mask, value in rows:
                    lines.append('            .{ .name = "%s", .mask = 0x%s, .value = 0x%s },' % (name, mask, value))
                lines.append('        },')
            lines.append('    },')
    return '\n'.join(lines + ['}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--idf', type=Path, default=Path('/home/valthon/esp/esp-idf-v5.5.1'))
    args = parser.parse_args()
    tag = subprocess.check_output(['git', '-C', str(args.idf), 'describe', '--tags', '--exact-match'], text=True).strip()
    if tag != 'v5.5.1':
        parser.error('--idf must point to the v5.5.1 tag')
    with tempfile.TemporaryDirectory(prefix='c6-idf-reference-') as directory:
        output = generate(build_runner(args.idf.resolve(), Path(directory)))
    if args.check:
        if DEST.read_text() != output:
            parser.exit(1, 'IDF fixtures differ; regenerate and review the changes\n')
        print('PASS: nine profiles and all PMU init table rows match compiled IDF v5.5.1')
    else:
        DEST.write_text(output)
        print(DEST)


if __name__ == '__main__':
    main()
