//! SSD1306 on an ESP32-C3 board with a 0.42" OLED (72x40 visible pixels).
//!
//! Wiring: display on I2C0 at address 0x3C (SDA = GPIO5, SCL = GPIO6), and an
//! active-low LED on GPIO8.
//!
//! The SSD1306 always drives a 128x64 frame; the 0.42" panel shows a 72x40
//! window of it. Images are therefore drawn into a full-size framebuffer at
//! the window's offset (`panel_x`, `panel_y`).

const std = @import("std");
const microzig = @import("microzig");
const ssd1306 = microzig.drivers.display.ssd1306;
const Duration = microzig.drivers.time.Duration;

const esp = microzig.hal;
const i2c = esp.i2c;
const gpio = esp.gpio;
const I2C_DatagramDevice = esp.drivers.I2C_DatagramDevice;
const sleep_ms = esp.time.sleep_ms;
const usb_serial_jtag = esp.usb_serial_jtag;

pub const panic = microzig.panic;

pub const std_options = microzig.std_options(.{
    .logFn = usb_serial_jtag.logger.log,
});

comptime {
    _ = microzig.export_startup();
}

var i2c0 = i2c.instance.num(0);
const sda_pin = gpio.num(5);
const scl_pin = gpio.num(6);
/// Active low: `put(0)` turns it on.
const led_pin = gpio.num(8);

const display_address: i2c.Address = @fromBackingInt(0x3C);
/// Bounds every I2C transaction, so a missing or stuck device produces
/// `error.Timeout` instead of hanging.
const i2c_timeout: Duration = .from_ms(100);

/// Size and position of the panel's visible window inside the 128x64 frame.
const panel_width = 72;
const panel_height = 40;
const panel_x = 27;
const panel_y = 24;

comptime {
    std.debug.assert(panel_x + panel_width <= ssd1306.Framebuffer.width);
    std.debug.assert(panel_y + panel_height <= ssd1306.Framebuffer.height);
}

/// A 72x40 image in SSD1306 page layout: each byte is a column of 8 pixels
