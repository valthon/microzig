/// Draws a 72x40 image into the panel's window of a black 128x64 framebuffer.
fn place_on_panel(image: *const PanelImage) ssd1306.Framebuffer {
    @setEvalBranchQuota(20_000);

    var fb: ssd1306.Framebuffer = .init(.black);
    for (0..panel_height) |y| {
        const bit: u3 = @intCast(y % 8);
        for (0..panel_width) |x| {
            if (image[x + (y / 8) * panel_width] & (@as(u8, 1) << bit) != 0)
                fb.set_pixel(@intCast(x + panel_x), @intCast(y + panel_y), .white);
        }
    }
    return fb;
}

const zig_logo = place_on_panel(&zig_logo_72x40);
const nothlav_logo = place_on_panel(&nothlav_logo_72x40);

fn blink_led() void {
    led_pin.put(0);
    sleep_ms(200);
    led_pin.put(1);
    sleep_ms(100);
}

fn setup_io() !void {
    led_pin.apply(.{
        .output_enable = true,
        .input_enable = false,
    });
    led_pin.put(1);

    i2c0.connect_pins(.{ .sda = sda_pin, .scl = scl_pin });
    try i2c0.apply(400_000);
}

pub fn main() !void {
    try setup_io();

    const display = try ssd1306.init(.i2c, I2C_DatagramDevice.init(i2c0, display_address, i2c_timeout), null);
    std.log.debug("display initialized", .{});

    for (0..3) |_| blink_led();

    try display.clear_screen(true);
    sleep_ms(500);
    try display.clear_screen(false);
    sleep_ms(500);

    const images = [_]*const ssd1306.Framebuffer{ &zig_logo, &nothlav_logo };
    while (true) {
        for (images) |image| {
            blink_led();
            try display.write_full_display(image.bit_stream());
            sleep_ms(2000);
        }
    }
}
